"""Turn B's frozen pilot (data/pilot.json, 353 real cs.LG/cs.AI papers) into seed files.

Writes
  db/seed/pilot.sql              INSERTs for A's schema (loaded by db/init on first start,
                                 or `psql "$DATABASE_URL" -f db/seed/pilot.sql` on Neon)
  db/seed/pilot_content.jsonl    {"paper_id", "abstract", "tldr"} per paper (contract 4 input
                                 for jobs/embed/embed_papers.py)

Usage (from the repo root):  python pipeline/pilot_to_seed.py path/to/pilot.json
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Column order of each entity list in pilot.json (same as B's scholarql/db.py COLUMNS),
# listed in foreign-key order so the file loads top to bottom
COLUMNS = {
    "institution": ("institution_id", "name", "country_code"),
    "venue": ("venue_id", "name", "venue_type"),
    "author": ("author_id", "name"),
    "topic": ("topic_id", "name", "parent_topic_id", "level"),
    "paper": (
        "paper_id",
        "title",
        "publication_year",
        "publication_date",
        "arxiv_id",
        "doi",
        "venue_id",
    ),
    "authorship": ("paper_id", "author_id", "author_order"),
    "author_affiliation": ("paper_id", "author_id", "institution_id"),
    "paper_topic": ("paper_id", "topic_id", "relevance", "is_primary"),
    "citation": ("citing_id", "cited_id", "source"),
}
BATCH = 500


def literal(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int | float):
        return repr(value)
    return "'" + str(value).replace("'", "''") + "'"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("pilot", type=Path)
    parser.add_argument("--out-dir", type=Path, default=ROOT / "db" / "seed")
    args = parser.parse_args()

    pilot = json.loads(args.pilot.read_text(encoding="utf-8"))
    entities = pilot["entities"]
    # Parents before children, so topic.parent_topic_id always points at an inserted row
    entities["topic"] = sorted(entities["topic"], key=lambda t: (t[3] is not None, t[3] or 0))

    args.out_dir.mkdir(parents=True, exist_ok=True)
    meta = pilot["metadata"]
    lines = [
        f"-- Generated by pipeline/pilot_to_seed.py from B's pilot ({meta['label']}, "
        f"snapshot {meta['snapshot']}). Do not edit by hand.",
        f"-- Scope: {meta['scope']}",
        "BEGIN;",
    ]
    for table, columns in COLUMNS.items():
        rows = entities[table]
        for start in range(0, len(rows), BATCH):
            values = ",\n".join(
                "(" + ",".join(literal(v) for v in row) + ")" for row in rows[start : start + BATCH]
            )
            lines.append(f"INSERT INTO {table} ({','.join(columns)}) VALUES\n{values};")
    lines += [
        "CALL compute_pagerank(30, 0.85);",
        "CALL refresh_analytics();",
        "COMMIT;",
        "ANALYZE;",
    ]
    sql_path = args.out_dir / "pilot.sql"
    sql_path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    content_path = args.out_dir / "pilot_content.jsonl"
    with content_path.open("w", encoding="utf-8", newline="\n") as out:
        for doc in pilot["documents"]:
            if doc.get("abstract"):
                record = {"paper_id": doc["paper_id"], "abstract": doc["abstract"], "tldr": None}
                out.write(json.dumps(record, ensure_ascii=False) + "\n")

    counts = ", ".join(f"{t} {len(entities[t])}" for t in COLUMNS)
    print(f"Wrote {sql_path} ({counts}) and {content_path}")


if __name__ == "__main__":
    main()
